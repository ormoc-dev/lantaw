/**
 * Reads .env (and process.env on Vercel) → writes src/config/env.js
 * Usage: node scripts/sync-env.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, ".env");
const outPath = path.join(root, "src", "config", "env.js");

function loadDotEnv(file) {
  if (!fs.existsSync(file)) return {};
  const out = {};
  for (const raw of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 1) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

const fileEnv = loadDotEnv(envPath);
const get = (key, fallback = "") =>
  String(process.env[key] || fileEnv[key] || fallback).trim();

const supabaseUrl = get("VITE_SUPABASE_URL");
const supabaseAnonKey = get("VITE_SUPABASE_ANON_KEY");
const siteUrl = get("VITE_SITE_URL", "http://localhost");
const tmdbApiKey = get("VITE_TMDB_API_KEY");
const tmdbBaseUrl = get("VITE_TMDB_BASE_URL", "https://api.themoviedb.org/3");
const tmdbImageBase = get("VITE_TMDB_IMAGE_BASE", "https://image.tmdb.org/t/p");
const omdbApiKey = get("VITE_OMDB_API_KEY");

const missing = [];
if (!supabaseUrl || supabaseUrl.includes("YOUR_PROJECT")) missing.push("VITE_SUPABASE_URL");
if (!supabaseAnonKey || supabaseAnonKey.includes("YOUR_")) missing.push("VITE_SUPABASE_ANON_KEY");
if (!tmdbApiKey || tmdbApiKey.includes("YOUR_")) missing.push("VITE_TMDB_API_KEY");

if (missing.length) {
  console.error(
    `sync-env: missing ${missing.join(", ")}.\n` +
      `Add them to .env (local) or Vercel Environment Variables, then re-run.`
  );
  process.exit(1);
}

const esc = (s) => JSON.stringify(String(s));

const source = fs.existsSync(envPath) ? ".env" : "process.env";
const contents = `/**
 * AUTO-GENERATED by scripts/sync-env.mjs from ${source}.
 * Do not edit by hand — change .env (or Vercel env vars) and run: npm run sync-env
 *
 * Supabase publishable/anon key is safe in the client (RLS protects data).
 * Never put the database password or service_role key in .env for this app.
 */

export const env = {
  supabaseUrl: ${esc(supabaseUrl)},
  supabaseAnonKey: ${esc(supabaseAnonKey)},
  siteUrl: ${esc(siteUrl)},
  tmdbApiKey: ${esc(tmdbApiKey)},
  tmdbBaseUrl: ${esc(tmdbBaseUrl)},
  tmdbImageBase: ${esc(tmdbImageBase)},
  omdbApiKey: ${esc(omdbApiKey)},
};

export function assertEnv() {
  const missing = [];
  if (!env.supabaseUrl || env.supabaseUrl.includes("YOUR_PROJECT")) {
    missing.push("supabaseUrl");
  }
  if (!env.supabaseAnonKey || env.supabaseAnonKey.includes("YOUR_SUPABASE")) {
    missing.push("supabaseAnonKey");
  }
  if (!env.tmdbApiKey || env.tmdbApiKey.includes("YOUR_TMDB")) {
    missing.push("tmdbApiKey");
  }
  return missing;
}
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, contents, "utf8");
console.log(`sync-env: wrote ${path.relative(root, outPath)}`);
